/** One document's selection of entries, and the `.tex` files written for it. */
import { readFile, readdir } from 'node:fs/promises'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { emitDocument, renderSection, resolveTemplate } from '../src/tex/emit'
import { documentSchema, selectEntries } from '../src/tex/documents'
import { dateRange } from '../src/primitives'
import type { Entry, PublicationGroup, PublicationList, Visibility } from '../src/shared/types'
import { project, writeFiles } from './support/project'

const options = (value: unknown = {}) => documentSchema.parse(value)
const rich = (text: string) => ({ text, html: text })
const talk = (title: string, date: number, kind: string, visibility: Visibility = 'public'): Entry =>
  ({ id: title, visibility, date: dateRange.parse(date), title: rich(title), kind })

const TALKS = [
  talk('invited-2025', 2025, 'invited'),
  talk('contributed-2024', 2024, 'contributed'),
  talk('private-2023', 2023, 'invited', 'private'),
  talk('cv-2021', 2021, 'seminar', 'cv'),
  talk('invited-2019', 2019, 'invited'),
]

describe('selectEntries', () => {
  const select = (value: unknown) => selectEntries(TALKS, options(value), 'talks').map(entry => entry.id)

  it('includes up to cv visibility by default', () => {
    expect(select({})).toEqual(['invited-2025', 'contributed-2024', 'cv-2021', 'invited-2019'])
    expect(select({ visibility: 'public' })).toEqual(['invited-2025', 'contributed-2024', 'invited-2019'])
  })

  it.each([
    [{ where: { kind: 'invited' } }, ['invited-2025', 'private-2023', 'invited-2019']],
    [{ where: { kind: ['contributed', 'seminar'] } }, ['contributed-2024', 'cv-2021']],
    [{ where: { year: '2024' } }, ['contributed-2024']],
    [{ where: { title: 'invited-2019' } }, ['invited-2019']],
    [{ since: 2023, until: 2024 }, ['contributed-2024', 'private-2023']],
    [{ where: { kind: 'invited' }, limit: 2 }, ['invited-2025', 'private-2023']],
  ])('selects %j', (section, expected) => {
    expect(select({ visibility: 'private', sections: { talks: section } })).toEqual(expected)
  })

  it('compares a link by its label', () => {
    const entries: Entry[] = [
      { id: 'a', visibility: 'public', institution: { label: 'TU Graz', url: 'https://tugraz.at' } },
      { id: 'b', visibility: 'public', referee: { label: 'Jane Doe', url: 'https://e.org' } },
    ]
    expect(selectEntries(entries, options({ sections: { x: { where: { institution: 'TU Graz' } } } }), 'x').map(entry => entry.id)).toEqual(['a'])
    expect(selectEntries(entries, options({ sections: { x: { where: { referee: 'Jane Doe' } } } }), 'x').map(entry => entry.id)).toEqual(['b'])
  })

  it.each([
    [{ sections: { talks: { filter: 'kind = invited' } } }],
    [{ sections: { talks: { limit: 0 } } }],
    [{ visibility: 'everyone' }],
    [{ publication: {} }],
    [{ publications: { groups: ['published'] } }],
  ])('rejects the options %j', (value) => {
    expect(documentSchema.safeParse(value).success).toBe(false)
  })
})

describe('emitDocument', () => {
  async function emit(sections: Record<string, Entry[]>, extra: { templates?: Record<string, string>, publications?: Record<string, PublicationList>, options?: unknown } = {}) {
    const root = await project(Object.fromEntries(Object.entries(extra.templates ?? {}).map(([name, source]) => [`templates/${name}`, source])))
    const outDir = join(root, 'generated')
    await emitDocument({
      sections,
      publications: extra.publications ?? {},
      options: options(extra.options),
      templateDir: join(root, 'templates'),
      outDir,
    })
    const files = (await readdir(outDir, { recursive: true })).filter(file => file.endsWith('.tex')).sort()
    return Object.fromEntries(await Promise.all(files.map(async file => [file, await readFile(join(outDir, file), 'utf8')])))
  }

  it('writes one file per section and one per publication list, with a header saying where to edit', async () => {
    const files = await emit({ talks: [talk('A talk', 2024, 'invited')] }, { publications: { recent: { count: 0, groups: [] } } })
    expect(Object.keys(files)).toEqual(['publications/recent.tex', 'talks.tex'])
    expect(files['talks.tex']).toBe('% Generated by vitakit. Do not edit; edit content/talks.yml instead.\n\\vitaentry{2024}{A talk}{}\n')
    expect(files['publications/recent.tex']).toBe('% Generated by vitakit. Do not edit; edit content/publications.bib or content/publication-lists.yml instead.\n\n')
  })

  it('escapes every field and keeps mathematics', async () => {
    const entry = { ...talk('Random $k$-ary trees', 2024, 'invited'), date: dateRange.parse('2024-03'), event: 'AofA & friends', location: 'a_b' }
    expect((await emit({ talks: [entry] }))['talks.tex']).toContain('\\vitaentry{Mar 2024}{Random $k$-ary trees}{AofA \\& friends, a\\_b}')
  })

  it('leaves no blank lines, which would end the paragraph a \\\\ continues', async () => {
    const entries: Entry[] = [
      { id: 'a', visibility: 'public', date: dateRange.parse(2024), degree: 'PhD', institution: { label: 'TU' }, thesis: { title: rich('T') }, note: 'N' },
      { id: 'b', visibility: 'public', date: dateRange.parse(2020), degree: 'MSc', institution: { label: 'TU' } },
    ]
    expect((await emit({ education: entries }))['education.tex'].split('\n').slice(1)).toEqual([
      '\\vitaentry{2024}{PhD}{TU}',
      '\\vitanote{Thesis: \\emph{T}}',
      '\\vitanote{N}',
      '\\vitaentry{2020}{MSc}{TU}',
      '',
    ])
  })

  it('uses the generic template for a section without its own', async () => {
    const entry: Entry = { id: 'o', visibility: 'public', title: rich('A visit'), audience: 'school', location: 'Graz', note: 'Fun' }
    expect((await emit({ outreach: [entry] }))['outreach.tex']).toContain('\\vitaentry{}{A visit}{Graz}\n\\vitanote{Fun}')
  })

  it('prefers a project template, named or generic, over the bundled ones', async () => {
    const templates = {
      'talks.eta': '<% for (const t of it.entries) { %>NAMED <%~ it.text(t.title) %><% } %>',
      '_generic.eta': '<% for (const t of it.entries) { %>GENERIC <%~ it.text(t.title) %><% } %>',
    }
    const files = await emit({ talks: [talk('A', 2024, 'x')], outreach: [talk('B', 2024, 'x')] }, { templates })
    expect(files['talks.tex']).toContain('NAMED A')
    expect(files['outreach.tex']).toContain('GENERIC B')
  })

  it('names the template that failed', async () => {
    await expect(emit({ talks: [talk('broken $k', 2024, 'x')] })).rejects.toThrow(/^template talks\.eta: .*talks\.eta: unbalanced math/)
    await expect(emit({ talks: [] }, { templates: { 'talks.eta': '<%~ it.nope() %>' } })).rejects.toThrow(/^template talks\.eta: /)
  })

  it('refuses a template that matches no section, suggesting the right name', async () => {
    await expect(emit({ talks: [] }, { templates: { 'talk.eta': '' } }))
      .rejects.toThrow(/cv-tex\/templates\/talk\.eta: no section is called "talk", so this template is never used; did you mean talks\.eta\?/)
  })

  it('cites a list\'s entries in its order and prints each group, labelled or not', async () => {
    const group = (id: string, keys: string[], label?: string): PublicationGroup =>
      ({ id, ...(label ? { label } : {}), count: keys.length, entries: keys.map(key => ({ key, html: '', badges: [], fields: {} })) })
    const publications = {
      years: { count: 3, groups: [group('years-1', ['b', 'c'], '2025'), group('years-2', ['a'], '2024')] },
      flat: { count: 1, groups: [group('flat-1', ['a'])] },
    }
    const files = await emit({}, { publications })
    expect(files['publications/years.tex']).toMatch(/\\begin\{refcontext\}\[sorting=none\]\n\\nocite\{b,c,a\}\n\\vitabibgroup\{years-1\}\{b,c\}\n\\printbibliography\[resetnumbers=true, check=vita-years-1, heading=subbibliography, title=\{2025\}\]/)
    expect(files['publications/flat.tex']).toContain('\\printbibliography[resetnumbers=true, check=vita-flat-1, heading=none]')
  })

  it('refuses a citation key that would break the LaTeX', async () => {
    const publications = { all: { count: 1, groups: [{ id: 'all-1', label: 'P', count: 1, entries: [{ key: 'doe%2024', html: '', badges: [], fields: {} }] }] } }
    await expect(emit({}, { publications })).rejects.toThrow(/"doe%2024" cannot be used as a citation key/)
  })
})

describe('templates', () => {
  it('reports where the effective one comes from, and can skip one', async () => {
    const templates = join(await project(), 'cv-tex/templates')
    await expect(resolveTemplate('talks', templates)).resolves.toMatchObject({ origin: 'bundled', generic: false })
    await expect(resolveTemplate('outreach', templates)).resolves.toMatchObject({ origin: 'bundled', generic: true })

    await writeFiles(templates, { 'talks.eta': 'local' })
    await expect(resolveTemplate('talks', templates)).resolves.toMatchObject({ origin: 'local', source: 'local' })
    // Replacing a local template starts from what would be used without it.
    await expect(resolveTemplate('talks', templates, { exclude: join(templates, 'talks.eta') }))
      .resolves.toMatchObject({ origin: 'bundled', generic: false })
  })

  it('render a section without writing files', async () => {
    const root = await project()
    const body = await renderSection('talks', TALKS, options({ sections: { talks: { limit: 1 } } }), join(root, 'cv-tex/templates'))
    expect(body).toContain('invited-2025')
    expect(body).not.toContain('contributed-2024')
    expect(await readdir(root)).toEqual([])
  })
})
