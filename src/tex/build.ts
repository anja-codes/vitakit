/**
 * Builds PDF documents: render `content/` into `cv-tex/generated/<doc>/`, then
 * run latexmk.
 *
 * No `-shell-escape`, no Python, no `.bbl` juggling: LaTeX only typesets what
 * is already on disk.
 */
import { spawn } from 'node:child_process'
import { copyFile, mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import process from 'node:process'
import { delimiter, join, resolve } from 'node:path'
import { loadContent } from '../content'
import { fail } from '../issues'
import { discoverDocuments, selectEntries, validateDocumentSections, type DocumentSource } from './documents'
import { publicationPlacementProblems } from '../placements'
import { discoverSections } from '../sections'
import { bundledTexDir, emitDocument, SITE_PATH_HELP } from './emit'
import { escapeTex, escapeUrl } from './escape'
import { isSitePath } from '../site-paths'
import type { VitakitContent } from '../shared/types'

/** The document class, resolved from `cv-tex/` when ejected. */
const CLASS_FILE = 'vitakit-cv.cls'

export interface BuildOptions {
  rootDir: string
  /** Build only these documents; all of them when empty. */
  only?: string[]
  /** Emit .tex but skip latexmk. */
  noPdf?: boolean
  /**
   * What happens to latexmk's output: shown as it runs (`inherit`, the
   * default), or kept back and only its end shown on failure (`capture`).
   */
  latexOutput?: 'inherit' | 'capture'
  /** Told about each finished step, for concise progress output. */
  onProgress?: (event: BuildEvent) => void
}

export type BuildEvent
  = | { document: string, step: 'tex', dir: string, files: number }
    | { document: string, step: 'pdf', file: string }

/** A tool of the TeX distribution is not installed. */
export class MissingToolError extends Error {
  constructor(readonly tool: string) {
    super(`${tool} not found; install a TeX distribution that includes latexmk and biber`)
    this.name = 'MissingToolError'
  }
}

function run(
  command: string,
  args: string[],
  cwd: string,
  env: NodeJS.ProcessEnv = {},
  output: 'inherit' | 'capture' = 'inherit',
  log?: string,
): Promise<void> {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { cwd, stdio: output === 'inherit' ? 'inherit' : ['ignore', 'pipe', 'pipe'], env: { ...process.env, ...env } })
    let captured = ''
    child.stdout?.on('data', (chunk: Buffer) => { captured += chunk.toString() })
    child.stderr?.on('data', (chunk: Buffer) => { captured += chunk.toString() })
    child.on('error', error => reject(
      (error as NodeJS.ErrnoException).code === 'ENOENT' ? new MissingToolError(command) : error,
    ))
    child.on('exit', (code) => {
      if (code === 0) return resolve()
      if (output === 'inherit') return reject(new Error(`${command} exited with code ${code}`))
      void readFile(log ?? '', 'utf8').catch(() => '').then((text) => {
        // TeX's own error, `! Undefined control sequence.` and the line it
        // happened in, says more than latexmk's summary of it.
        const lines = text.split('\n')
        const start = lines.findIndex(line => line.startsWith('! '))
        const excerpt = start === -1
          ? captured.trim().split('\n').slice(-25).join('\n')
          : lines.slice(start, start + 8).join('\n').trim()
        reject(new Error(`${command} exited with code ${code}${excerpt ? `\n\n${excerpt}` : ''}${log ? `\n\nFull log: ${log}` : ''}`))
      })
    })
  })
}

/**
 * Header data and per-document selection metadata; and, with
 * `profile.url`, a biblatex sourcemap that makes a `url` in the .bib file that
 * is a path on the site (`/papers/x.pdf`) absolute, as biblatex prints it.
 */
function profilePreamble(content: VitakitContent, document: DocumentSource, lists: string[]): string {
  const { profile } = content
  const href = (url: string) => {
    if (isSitePath(url)) fail('content/profile.yml', `links: ${url} ${SITE_PATH_HELP}`)
    return escapeUrl(url)
  }
  const affiliation = profile.affiliation?.label ? escapeTex(profile.affiliation.label) : ''
  const tagline = [profile.title && escapeTex(profile.title), affiliation].filter(Boolean).join(', ')
  const contact = [
    profile.email && `\\href{mailto:${escapeUrl(profile.email)}}{${escapeTex(profile.email)}}`,
    ...profile.links.map(link => `\\href{${href(link.url)}}{${escapeTex(link.label)}}`),
  ].filter(Boolean).join(' \\quad ')

  return [
    `% Generated by vitakit. Do not edit; edit content/profile.yml or cv-tex/${document.name}.yml instead.`,
    `\\vitaname{${escapeTex(profile.name)}}`,
    `\\vitatagline{${tagline}}`,
    `\\vitacontact{${contact}}`,
    ...(profile.url ? siteUrlSourcemap(profile.url) : []),
    ...Object.entries(content.sections).flatMap(([id, entries]) => {
      const title = document.options.sections[id]?.title
      return [
        ...(selectEntries(entries, document.options, id).length ? [] : [`\\vitaemptysection{${id}}`]),
        ...(title ? [`\\vitasectiontitle{${id}}{${escapeTex(title)}}`] : []),
      ]
    }),
    ...lists.filter(name => !content.publications[name]?.count).map(name => `\\vitaemptypublications{${name}}`),
    '',
  ].join('\n')
}

/** Rewrites `url = {/papers/x.pdf}` to an absolute URL below the site's address. */
function siteUrlSourcemap(siteUrl: string): string[] {
  const base = siteUrl.replace(/\/?$/, '/')
  // Written into a TeX argument and a Perl substitution: nothing that either
  // would interpret. A site's address needs none of it.
  if (!/^https?:\/\/[\w.:/-]+$/.test(base)) {
    fail('content/profile.yml', `url: ${siteUrl} may only contain letters, digits and - . _ : /`)
  }
  return [
    '\\ifdefined\\DeclareSourcemap',
    `  \\DeclareSourcemap{\\maps[datatype=bibtex]{\\map{\\step[fieldsource=url, match=\\regexp{\\A/}, replace={${base}}]}}}`,
    '\\fi',
  ]
}

async function buildDocument(
  document: DocumentSource,
  content: VitakitContent,
  options: BuildOptions,
  cvDir: string,
): Promise<void> {
  const outDir = join(cvDir, 'generated', document.name)
  const lists = [...new Set(document.publications.map(placement => placement.list))]
  const written = await emitDocument({
    sections: content.sections,
    publications: Object.fromEntries(lists.map(name => [name, content.publications[name]!])),
    siteUrl: content.profile.url,
    options: document.options,
    templateDir: join(cvDir, 'templates'),
    outDir,
  })
  await writeFile(join(outDir, 'profile.tex'), profilePreamble(content, document, lists))

  // The document class lives in the package and is copied into the generated
  // directory -- which vitakit owns and .gitignore excludes -- rather than into
  // cv-tex/, so a build never modifies files the user is editing.
  //
  // An ejected class must still win, and TEXINPUTS cannot arrange that: with
  // `-outdir`, TeX searches the output directory *before* the current one, so a
  // generated copy would shadow `cv-tex/vitakit-cv.cls`. The generated copy is
  // therefore only written when the user has not ejected one, and a stale copy
  // from an earlier build is removed.
  const generatedClass = join(outDir, CLASS_FILE)
  if (existsSync(join(cvDir, CLASS_FILE))) await rm(generatedClass, { force: true })
  else await copyFile(join(bundledTexDir, CLASS_FILE), generatedClass)

  options.onProgress?.({ document: document.name, step: 'tex', dir: outDir, files: written.length + 1 })
  if (options.noPdf) return

  // Everything latexmk writes (.aux, .bcf, .fls, .log, the PDF) goes to the
  // generated directory; only the finished PDF is moved next to the source, so
  // `cv-tex/` keeps holding nothing but files the user wrote.
  const relativeOut = join('generated', document.name)
  await run('latexmk', [
    '-pdf',
    '-halt-on-error',
    '-interaction=nonstopmode',
    `-outdir=${relativeOut}`,
    // Otherwise -outdir can shadow teaching.tex with its generated section.
    resolve(document.texFile),
  ], cvDir, {
    // A trailing delimiter keeps the standard search paths.
    TEXINPUTS: `.${delimiter}${relativeOut}${delimiter}${process.env.TEXINPUTS ?? ''}`,
  }, options.latexOutput, join(outDir, `${document.name}.log`))
  await rename(join(outDir, `${document.name}.pdf`), join(cvDir, `${document.name}.pdf`))
  options.onProgress?.({ document: document.name, step: 'pdf', file: join(cvDir, `${document.name}.pdf`) })
}

export async function buildCv(options: BuildOptions): Promise<string[]> {
  const cvDir = join(options.rootDir, 'cv-tex')
  if (!existsSync(cvDir)) {
    throw new Error(`no cv-tex/ directory in ${options.rootDir}`)
  }

  // Documents may include entries the website never sees.
  const content = await loadContent(options.rootDir, { strict: true, maxVisibility: 'private', target: 'pdf' })
  const documents = await discoverDocuments(cvDir)
  const sources = await discoverSections(options.rootDir)

  for (const document of documents) {
    validateDocumentSections(document, sources)
    const [problem] = publicationPlacementProblems([], [...document.placements, ...document.publications], Object.keys(content.publications))
    if (problem) fail(problem.where, problem.message)
  }

  const unknown = options.only?.filter(name => !documents.some(document => document.name === name)) ?? []
  if (unknown.length) {
    const known = documents.map(document => document.name).join(', ')
    throw new Error(`no document matched ${unknown.join(', ')}; available: ${known}`)
  }
  const selected = options.only?.length
    ? documents.filter(document => options.only!.includes(document.name))
    : documents

  await mkdir(join(cvDir, 'generated'), { recursive: true })
  for (const document of selected) {
    await buildDocument(document, content, options, cvDir)
  }

  return selected.map(document => join(cvDir, `${document.name}.pdf`))
}

/** Read a generated file, for tests and diagnostics. */
export async function readGenerated(rootDir: string, document: string, section: string): Promise<string> {
  return readFile(join(rootDir, 'cv-tex', 'generated', document, `${section}.tex`), 'utf8')
}
