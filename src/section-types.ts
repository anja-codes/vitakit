/**
 * `.nuxt/vitakit/sections.d.ts`: one key of `VitakitSections` per section,
 * typed by its schema, so that `useSection('talks')` and the slots of
 * `<VitaSection id="talks">` are typed by `schemas/talks.ts` (or the built-in
 * schema).
 *
 * Only which sections exist and where their schemas are is written down; the
 * types themselves are TypeScript's reading of the schema files, so a field
 * added to a schema is typed at once. A section added or removed, or a schema
 * file created or deleted, rewrites this file.
 */
import { existsSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import { schemas } from './schemas'
import { findSectionFiles } from './sections'

/** Where each section's schema comes from: a file of the project's, or a built-in one. */
export interface SectionTypeSource {
  id: string
  /** Absolute path of `schemas/<id>.ts`, when the project has one. */
  file?: string
  builtIn: boolean
}

/** The sections in `content/` and their schemas; sections with neither are left out. */
export async function sectionTypeSources(rootDir: string): Promise<SectionTypeSource[]> {
  const { files } = await findSectionFiles(rootDir).catch(() => ({ files: [] }))
  return files
    .map(({ id }) => {
      const file = join(rootDir, 'schemas', `${id}.ts`)
      return { id, ...(existsSync(file) ? { file } : {}), builtIn: Object.hasOwn(schemas, id) }
    })
    .filter(source => source.file !== undefined || source.builtIn)
}

/** The declaration file, for a build directory (paths to schemas are relative to it). */
export function sectionTypesDeclaration(sources: SectionTypeSource[], buildDir: string): string {
  const dir = join(buildDir, 'vitakit')
  const lines = sources.map(({ id, file }) => {
    const schema = file !== undefined
      ? `typeof import('${relative(dir, file).split(sep).join('/').replace(/\.ts$/, '')}').default`
      : `typeof import('@anja.codes/vitakit').schemas[${JSON.stringify(id)}]`
    return `    ${JSON.stringify(id)}: SectionEntry<${schema}>`
  })
  return [
    '// Generated by vitakit from content/*.yml and schemas/; do not edit.',
    `import type { SectionEntry } from '@anja.codes/vitakit/shared'`,
    `declare module '@anja.codes/vitakit/shared' {`,
    `  interface VitakitSections {`,
    ...lines,
    `  }`,
    `}`,
    `export {}`,
    '',
  ].join('\n')
}
